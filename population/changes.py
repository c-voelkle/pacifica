"""Workbook change list: what the People and Paths sheets would need to match the
approved population model (author decisions of 27 October 2026).

The workbook is read, never written. Output:
  population/outputs/workbook_changes.csv  year-by-year proposed inputs and memo series
  population/outputs/workbook_changes.md   key-year summary for the change list

Run:  python3 population/changes.py
"""
from __future__ import annotations

import csv
import sys
from pathlib import Path

import openpyxl

import canon
from cohort import load

OUT = Path(__file__).resolve().parent / "outputs"
KEY = [1850, 1856, 1861, 1865, 1870, 1880, 1887, 1895, 1900, 1907, 1914, 1920, 1925, 1932]


def sheet_extra() -> dict[int, dict]:
    """People columns the model run doesn't read: Asian-origin stocks and share."""
    wb = openpyxl.load_workbook(canon.WORKBOOK, read_only=True, data_only=True)
    cols = {"N": "chinese_origin", "O": "japanese_origin", "P": "filipino_origin",
            "Q": "asian_guest", "R": "asian_talent", "S": "asian_share"}
    idx = {openpyxl.utils.column_index_from_string(c) - 1: k for c, k in cols.items()}
    out: dict[int, dict] = {}
    for row in wb["People"].iter_rows(min_row=6, values_only=True):
        if row and isinstance(row[0], (int, float)) and canon.FIRST <= row[0] <= canon.LAST:
            out[int(row[0])] = {k: float(row[i] or 0.0) for i, k in idx.items()}
    return out


def build() -> list[dict]:
    rows, meta = canon.run()          # approved scenario: canon rates, DEM-01, origin shares
    sheet = meta["sheet"]
    extra = sheet_extra()
    by_end = {r["year"]: r for r in rows}          # row "year" = end of year (year + 1)
    out = []
    start = sheet[canon.FIRST]["start"]
    for y in range(canon.FIRST, canon.LAST + 1):
        r = by_end[y + 1]
        d = sheet[y]
        k = canon.early_multiplier(y)
        asian_model = r["chinese"] + r["japanese"] + r["filipino"]
        out.append({
            "year": y,
            "paths_C_sheet": d["ni_rate"],
            "paths_C_model": r["model_natural_increase"] / start if start else 0.0,
            "paths_E_sheet": d["am_eu"], "paths_E_proposed": d["am_eu"] * k,
            "paths_F_sheet": d["chinese"], "paths_F_proposed": d["chinese"] * k,
            "end_sheet": d["end"], "end_model": r["model_total"],
            "native_hawaiian_model": r["native_hawaiian"],
            "native_californian_model": r["native_californian"],
            "chinese_origin_model": r["chinese"], "japanese_origin_model": r["japanese"],
            "filipino_origin_model": r["filipino"],
            "asian_origin_sheet": sum(extra[y][c] for c in ("chinese_origin", "japanese_origin", "filipino_origin",
                                                            "asian_guest", "asian_talent")),
            "asian_share_sheet": extra[y]["asian_share"],
            "asian_share_model": asian_model / r["model_total"],
            "japanese_vs_chinese_sheet": (extra[y]["japanese_origin"], extra[y]["chinese_origin"]),
        })
        start = r["model_total"]
    return out


def fmt(x: float) -> str:
    return f"{x:,.0f}"


def main() -> int:
    OUT.mkdir(exist_ok=True)
    rows = build()
    keys = [k for k in rows[0] if k != "japanese_vs_chinese_sheet"]
    with open(OUT / "workbook_changes.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(keys)
        for r in rows:
            w.writerow([round(r[k], 6) if isinstance(r[k], float) else r[k] for k in keys])
    by = {r["year"]: r for r in rows}
    dem = load("assumptions")["dem01"]
    L = ["# Workbook changes implied by the population model", "",
         "Generated by `population/changes.py` (approved scenario: canon rates, DEM-01, talent stream split by origin). "
         "The workbook is not changed. Year-by-year values: `workbook_changes.csv`. "
         "Residents are at the end of each year, as in People column L.", "",
         "## Residents and the natural-increase rate (People L, Paths C)", "",
         "| Year | Sheet residents | Model residents | Gap | Paths C now | Paths C proposed |",
         "|---|---|---|---|---|---|"]
    for y in KEY:
        r = by[y]
        L.append(f"| {y} | {fmt(r['end_sheet'])} | {fmt(r['end_model'])} | {(r['end_model'] / r['end_sheet'] - 1) * 100:+.1f}% "
                 f"| {r['paths_C_sheet'] * 100:.2f}% | {r['paths_C_model'] * 100:.2f}% |")
    span = [by[y] for y in range(dem["from"], dem["to"] + 1)]
    L += ["", f"## Early arrivals (Paths E and F, {dem['from']}–{dem['to']}, × {dem['multiplier']:.2f})", "",
          f"Americas & Europe: {fmt(sum(r['paths_E_sheet'] for r in span))} → {fmt(sum(r['paths_E_proposed'] for r in span))}. "
          f"Chinese: {fmt(sum(r['paths_F_sheet'] for r in span))} → {fmt(sum(r['paths_F_proposed'] for r in span))}.", "",
          "## Memo series the sheet doesn't have", "",
          "| Year | Native Hawaiians | Native Californians | Chinese-origin | Japanese-origin | Filipino-origin | Asian-origin share: sheet | model |",
          "|---|---|---|---|---|---|---|---|"]
    for y in KEY:
        r = by[y]
        L.append(f"| {y} | {fmt(r['native_hawaiian_model'])} | {fmt(r['native_californian_model'])} "
                 f"| {fmt(r['chinese_origin_model'])} | {fmt(r['japanese_origin_model'])} | {fmt(r['filipino_origin_model'])} "
                 f"| {r['asian_share_sheet'] * 100:.1f}% | {r['asian_share_model'] * 100:.1f}% |")
    j, c = by[1932]["japanese_vs_chinese_sheet"]
    L += ["", f"The sheet's own stream columns (People N and O, without the talent and guest-worker stocks) give "
          f"{fmt(c)} Chinese-Pacificans and {fmt(j)} Japanese-Pacificans in 1932."]
    (OUT / "workbook_changes.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    sys.exit(main())
